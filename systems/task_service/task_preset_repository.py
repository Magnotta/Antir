"""
Read/write access to the flat-file TaskPreset registry at task_presets.py.

Presets are stored as literal `TaskPreset(...)` constructor calls so the
file stays human-readable and diffable in git, instead of living in JSON
or a DB table. Shared load/save/add/search plumbing lives in
systems/common/preset_file.py; this module supplies TaskPreset's own path,
dict name, file header, and search behavior (matched against name/notes,
same as before).
"""

from __future__ import annotations

from pathlib import Path

from systems.preset_repository import (
    add_preset as _add_preset,
    load_presets as _load_presets,
    save_presets as _save_presets,
    search_presets as _search_presets,
)
from systems.task_service.task_presets import TaskPreset

PRESETS_PATH = Path(__file__).with_name("task_presets.py")
DICT_NAME = "TASK_PRESETS_DICT"
HEADER = (
    '"""\nFlat-file registry of TaskPreset objects.\n\n'
    "Auto-generated by task_preset_repository.save_presets() -- avoid\n"
    "hand-editing while the app is running, the next save() overwrites\n"
    'this file.\n"""\n\n'
    "from core.defs import SkillTrack\n"
    "from systems.task_service.task import (\n"
    "\tInterruptibility,\n"
    "\tTechnicality,\n"
    "\tTaskPreset,\n"
    ")\n\n\n"
)


def _search_key(key: str, preset: TaskPreset) -> str:
    return f"{preset.name} {preset.notes or ''}"


def load_presets(
    path: Path = PRESETS_PATH,
) -> dict[str, TaskPreset]:
    return _load_presets(path, DICT_NAME)


def search_presets(
    presets: dict[str, TaskPreset], query: str | None
) -> list[TaskPreset]:
    """Case-insensitive substring match against name or notes."""
    return _search_presets(
        presets, query, search_key=_search_key
    )


def save_presets(
    presets: dict[str, TaskPreset],
    path: Path = PRESETS_PATH,
) -> None:
    """Regenerate task_presets.py wholesale from `presets`."""
    _save_presets(
        path,
        DICT_NAME,
        HEADER,
        presets,
        value_type="TaskPreset",
    )


def add_preset(
    preset: TaskPreset, path: Path = PRESETS_PATH
) -> dict[str, TaskPreset]:
    """Add one preset (keyed by name) and persist the whole dict.

    Returns the new dict. Overwrites any existing preset with the same
    name.
    """
    return _add_preset(
        path,
        DICT_NAME,
        HEADER,
        preset.name,
        preset,
        value_type="TaskPreset",
    )
