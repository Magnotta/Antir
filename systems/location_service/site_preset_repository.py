"""
Read/write access to the flat-file SitePreset registry at site_presets.py.

Mirrors task_preset_repository.py; shared load/save/add/search plumbing
lives in systems/common/preset_file.py. A site_presets.py file (even just
`SITE_PRESETS_DICT: dict[str, SitePreset] = {}`) must exist before the
first load_presets() call, same as task_presets.py does today.
"""

from __future__ import annotations

from pathlib import Path

from systems.preset_repository import (
    add_preset as _add_preset,
    load_presets as _load_presets,
    save_presets as _save_presets,
    search_presets as _search_presets,
)
from systems.location_service.site_presets import SitePreset

PRESETS_PATH = Path(__file__).with_name("site_presets.py")
DICT_NAME = "SITE_PRESETS_DICT"
HEADER = (
    '"""\n'
    "Flat-file registry of SitePreset objects.\n\n"
    "Auto-generated by site_preset_repository.save_presets() -- avoid\n"
    "hand-editing while the app is running, the next save() overwrites\n"
    "this file.\n"
    '"""\n\n'
    "from systems.site_service.site import SitePreset\n\n"
)


def load_presets(
    path: Path = PRESETS_PATH,
) -> dict[str, SitePreset]:
    return _load_presets(path, DICT_NAME)


def search_presets(
    presets: dict[str, SitePreset], query: str | None
) -> list[SitePreset]:
    # SitePreset has no name/notes of its own (see site.py) -- presets are
    # matched by their dict key alone, which is the shared default.
    return _search_presets(presets, query)


def save_presets(
    presets: dict[str, SitePreset],
    path: Path = PRESETS_PATH,
) -> None:
    _save_presets(
        path,
        DICT_NAME,
        HEADER,
        presets,
        value_type="SitePreset",
    )


def add_preset(
    key: str, preset: SitePreset, path: Path = PRESETS_PATH
) -> dict[str, SitePreset]:
    return _add_preset(
        path,
        DICT_NAME,
        HEADER,
        key,
        preset,
        value_type="SitePreset",
    )
